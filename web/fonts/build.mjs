// Vendors the brand typefaces into internal/api/assets/fonts, served from the
// app origin and never a third-party CDN (Exh-wjqh; both fonts are SIL OFL).
// Sources are the exact-pinned @fontsource-variable packages (versions and
// integrity hashes are fixed by package.json + package-lock.json). Their
// "latin" files already cover Basic Latin, Latin-1 and general punctuation.
//
//  - Schibsted Grotesk: one variable woff2, narrowed to wght 400..800, the
//    weights the app's CSS uses.
//  - Fraunces: a STATIC upright instance pinned at opsz 72,
//    wght 600, SOFT 100, WONK 0. A static file is a fraction of the variable
//    font and there is exactly one headline style (page title), so nothing
//    else is needed. A static instance has no variation axes, so
//    font-variation-settings cannot change it; widen this build to ship
//    another weight or setting.
//
// Instancing needs python3 + fontTools + brotli, as the Phosphor subset step
// does (the Dockerfile's asset stage installs them). Unlike that step, this
// one has no useful fallback: shipping the full variable Fraunces would be
// ~10x larger, so a missing toolchain fails the build.
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, statSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = (name, ...rest) => path.join(here, "node_modules/@fontsource-variable", name, ...rest);
const outDir = path.join(here, "../../internal/api/assets/fonts");
mkdirSync(outDir, { recursive: true });

function instance(source, out, axes) {
  try {
    execFileSync("python3", ["-m", "fontTools.varLib.instancer", source, ...axes,
      "-o", path.join(outDir, out)], { stdio: "pipe" });
  } catch (err) {
    throw new Error(`fonts: instancing ${out} failed — python3 with fonttools and brotli is required ` +
      `(apt install python3-fonttools python3-brotli): ${String(err.stderr || err.message).split("\n").slice(-3).join(" ")}`);
  }
}

const headline = ["opsz=72", "wght=600", "SOFT=100", "WONK=0"];
instance(pkg("schibsted-grotesk", "files/schibsted-grotesk-latin-wght-normal.woff2"), "schibsted-grotesk.woff2", ["wght=400:800"]);
instance(pkg("fraunces", "files/fraunces-latin-full-normal.woff2"), "fraunces-600.woff2", headline);

copyFileSync(pkg("schibsted-grotesk", "LICENSE"), path.join(outDir, "LICENSE-schibsted-grotesk.txt"));
copyFileSync(pkg("fraunces", "LICENSE"), path.join(outDir, "LICENSE-fraunces.txt"));

// Relative url()s resolve inside the versioned /assets/v/<build>/ tree, so
// the font URLs are versioned and immutable like every other asset.
const css = `/* Generated by web/fonts/build.mjs. Brand typefaces, SIL OFL (see LICENSE-*.txt). */
@font-face{font-family:"Schibsted Grotesk";font-style:normal;font-weight:400 800;font-display:swap;src:url("./schibsted-grotesk.woff2") format("woff2")}
@font-face{font-family:Fraunces;font-style:normal;font-weight:600;font-display:swap;src:url("./fraunces-600.woff2") format("woff2")}
`;
writeFileSync(path.join(outDir, "fonts.css"), css);

const sizes = ["schibsted-grotesk", "fraunces-600"]
  .map((n) => `${n} ${statSync(path.join(outDir, n + ".woff2")).size}B`).join(", ");
console.log(`Vendored brand fonts -> ${path.relative(process.cwd(), outDir)} (${sizes})`);
